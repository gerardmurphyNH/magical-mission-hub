"""Generate the printable Tooth Fairy letter variants as standalone HTML.

Each variant reuses the exact styles of tooth-fairy-letter-template.html (the
moon-and-stars letter design), so every printable on /tooth-fairy-letter
matches. Wording comes from the site's existing copy: the short-notes section,
the letter maker's "letter to the Tooth Fairy" prompts, and the certificate's
quality list.

Run from the repo root, then render each file to PDF + JPG:

    python3 scripts/printables/build-letter-variants.py
    for n in tooth-fairy-first-tooth-letter tooth-fairy-goodbye-letter \
             tooth-fairy-late-letter letter-to-the-tooth-fairy-from-child; do
      "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" --headless=new \
        --no-pdf-header-footer --print-to-pdf=public/downloads/$n.pdf \
        scripts/printables/$n.html
      pdftoppm -jpeg -jpegopt quality=88 -r 180 -singlefile \
        public/downloads/$n.pdf public/downloads/$n
    done

Check each PDF is exactly 1 page (pdfinfo) and nothing is clipped.
"""
import re
from pathlib import Path

HERE = Path(__file__).parent
template = (HERE / "tooth-fairy-letter-template.html").read_text()
STYLE = re.search(r"<style>[\s\S]*?</style>", template.split("<body>")[1]).group(0)

EXTRA_CSS = """
<style>
  @page { size: letter; margin: 0.4in 0.45in; }
  html, body { margin: 0; background: #fff; }
  .wtw-letter .wtw-letter__kicker {
    margin: .55rem 0 0;
    font: .72rem / 1.3 Futura, system-ui, sans-serif;
    letter-spacing: .18em;
    text-transform: uppercase;
    color: var(--wtw-letter-gold);
  }
  /* Kid fill-in version: bigger writing room, fewer lines. */
  .wtw-letter--kid .wtw-letter__blank { block-size: 1.7em; }
  .wtw-letter--kid .wtw-letter__line {
    block-size: 2.1em;
    border-block-end: 1px solid var(--wtw-letter-lavender);
    margin-block-end: .35em;
  }
  .wtw-letter--kid .wtw-letter__body p { margin-block-end: 1.25em; }
  .wtw-letter__qualities {
    display: grid;
    grid-template-columns: repeat(3, 1fr);
    gap: .55em 1em;
    margin: .2em 0 1.2em;
    font-size: .95em;
  }
  .wtw-letter__qualities span::before {
    content: "";
    display: inline-block;
    inline-size: .85em;
    block-size: .85em;
    margin-inline-end: .45em;
    border: 1.5px solid var(--wtw-letter-lavender);
    border-radius: 50%;
    vertical-align: -.1em;
  }
</style>
"""


def blank(label: str) -> str:
    return (
        '<span class="wtw-letter__answer"><span class="wtw-letter__blank" '
        f'role="img" aria-label="{label}"></span>'
    )


def prompt(text: str, label: str, end: str = ".", magic: bool = False) -> str:
    cls = "wtw-letter__prompt wtw-letter__prompt--magic" if magic else "wtw-letter__prompt"
    return f'<p class="{cls}">\n      <span>{text}</span>\n      {blank(label)}{end}</span>\n    </p>'


def greeting(label="Blank for the child’s name") -> str:
    return (
        '<p class="wtw-letter__prompt wtw-letter__prompt--greeting">\n'
        f'      <span>Dear</span>\n      {blank(label)},</span>\n    </p>'
    )


def page(slug: str, title: str, heading: str, kicker: str, body: str, signoff: str,
         footer: str, kid: bool = False) -> str:
    return f"""<!doctype html>
<!--
  Source for public/downloads/{slug}.pdf and .jpg (linked from /tooth-fairy-letter).
  GENERATED by scripts/printables/build-letter-variants.py - edit that file, not this one.
  Fonts (Baskerville, Snell Roundhand, Futura) are macOS system fonts; render on a Mac.
-->
<html lang="en">
<head>
<meta charset="utf-8">
<title>{title} | Wiggly Tooth Workshop</title>
<meta name="author" content="Wiggly Tooth Workshop">
{STYLE}
{EXTRA_CSS}
</head>
<body>
<article class="wtw-letter{' wtw-letter--kid' if kid else ''}" aria-label="{title}">
  <header class="wtw-letter__header">
    <div class="wtw-letter__moonlight" aria-hidden="true">
      <span class="wtw-letter__moon"></span>
      <span class="wtw-letter__star wtw-letter__star--west"></span>
      <span class="wtw-letter__star wtw-letter__star--north"></span>
      <span class="wtw-letter__star wtw-letter__star--east"></span>
    </div>
    <h3 class="wtw-letter__title">{heading}</h3>
    <div class="wtw-letter__divider" aria-hidden="true"><span class="wtw-letter__star"></span></div>
    <p class="wtw-letter__kicker">{kicker}</p>
  </header>
  <div class="wtw-letter__body">
    {body}
  </div>
  <div class="wtw-letter__signoff">
    <span class="wtw-letter__star" aria-hidden="true"></span>
    <span class="wtw-letter__signoff-rule" aria-hidden="true"></span>
    <p class="wtw-letter__signature">{signoff}</p>
  </div>
  <footer class="wtw-letter__footer">
    <a href="https://wigglytoothworkshop.com/tooth-fairy-letter">{footer}</a>
  </footer>
</article>
</body>
</html>
"""


